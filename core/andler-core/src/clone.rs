//! `CloneMode` — три режима клонирования диска Android-инстанса,
//! используемые `Daemon::clone_instance` (`andler-daemon`) и реализуемые
//! на уровне файлов qcow2 в `andler-disk::clone`.
//!
//! Это не часть `config::InstanceConfig` (тип не описывает конфигурацию
//! инстанса — он описывает *операцию* клонирования одного инстанса в
//! другой), поэтому модуль расположен на верхнем уровне крейта, рядом с
//! `android_profile`, а не внутри `config/`.

/// Режим, в котором `Daemon::clone_instance` создаёт диск нового
/// инстанса из диска существующего. См. историю проекта (обсуждение
/// `CloneInstance`) за полным архитектурным обоснованием всех трёх
/// вариантов — здесь только итоговый контракт.
///
/// Применимо только к `InstanceKind::AndroidVm` — у `InstanceKind::LinuxVm`
/// нет общего `base_image`/управляемого `instances_root`, клонирование
/// для него за пределами текущего шага (см. `Daemon::clone_instance`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CloneMode {
    /// Новый диск — overlay с `backing_file`, указывающим прямо на диск
    /// инстанса-источника (не на общий `base_image`). Дешёво и быстро
    /// (`qemu-img create -b`, без копирования данных), но вводит
    /// зависимость клона от источника: `remove_instance(purge=true)` на
    /// источнике отказывает, пока у него есть живые `Linked`-клоны (см.
    /// `Daemon::find_live_clones`) — иначе backing_file клона исчез бы.
    Linked,
    /// Новый диск — полностью самостоятельный файл без какого-либо
    /// `backing_file`: вся backing chain источника (диск инстанса +,
    /// если применимо, общий `base_image`) разворачивается в один файл
    /// (`qemu-img convert`). Дорого по месту (полный логический размер,
    /// не разница) и по времени, но результат не зависит ни от
    /// источника, ни от общего базового образа — переживает удаление
    /// обоих.
    FullStandalone,
    /// Новый диск — побайтовая копия самого файла диска источника
    /// (обычный `cp`, не `qemu-img`). Работает благодаря тому, что
    /// Android-overlay уже содержит только diff относительно общего
    /// `base_image` — копия остаётся маленькой и тонкой относительно
    /// него же (наследует тот же `backing_file` из метаданных
    /// скопированного файла), но физически не зависит от источника
    /// после копирования: в отличие от `Linked`, переживает
    /// `remove_instance(purge=true)` на источнике без каких-либо
    /// ограничений.
    SharedBase,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn clone_mode_variants_are_distinct() {
        // Тривиальная проверка, что три варианта действительно различны
        // как значения — защита от случайной опечатки типа `derive`,
        // из-за которой два варианта схлопнулись бы в PartialEq
        // (не происходит для простого C-style enum, но дёшево
        // зафиксировать как явное намерение).
        assert_ne!(CloneMode::Linked, CloneMode::FullStandalone);
        assert_ne!(CloneMode::Linked, CloneMode::SharedBase);
        assert_ne!(CloneMode::FullStandalone, CloneMode::SharedBase);
    }
}
